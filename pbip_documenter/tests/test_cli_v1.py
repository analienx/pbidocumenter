"""Public, machine-readable PBIP Documenter CLI v1 contract."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import pytest

from pbip_documenter import bootstrap

FIXTURE = Path(__file__).resolve().parents[2] / "examples" / "contoso-retail"


def call_json(capsys: pytest.CaptureFixture[str], args: list[str]) -> tuple[int, dict[str, Any]]:
    code = bootstrap.main(args)
    captured = capsys.readouterr()
    assert not captured.err, captured.err
    assert captured.out.count("\n") == 1, f"Expected exactly one JSON line: {captured.out[:300]}"
    payload = json.loads(captured.out)
    assert payload["schema_version"] == "1.0"
    assert code == payload["exit_code"]
    return code, payload


def test_validate_contoso_and_parser_limit(capsys: pytest.CaptureFixture[str]) -> None:
    code, data = call_json(capsys, ["validate", str(FIXTURE), "--strict", "--json"])
    assert code == 0
    assert data["projects"][0]["valid"] is True
    assert data["projects"][0]["parser"]["mode"] == "python_fallback"
    assert data["projects"][0]["parser"]["full_tmdl_grammar_verified"] is False


def test_inspect_safe_inventory_and_stable_fingerprint(capsys: pytest.CaptureFixture[str]) -> None:
    code, result = call_json(capsys, ["inspect", str(FIXTURE), "--details", "--json"])
    assert code == 0
    project = result["projects"][0]
    assert project["inventory"]["tables"] == 12
    assert project["inventory"]["measures"] == 55
    assert project["inventory"]["relationships"] == 19
    assert project["inventory"]["report_visuals"] == 54
    assert "Fact Sales" in project["inventory"]["table_names"]
    assert len(project["source_sha256"]) == 64
    assert "connection_string" not in json.dumps(result).lower()


def test_inspect_fingerprint_is_deterministic(capsys: pytest.CaptureFixture[str]) -> None:
    _, first = call_json(capsys, ["inspect", str(FIXTURE), "--json"])
    _, second = call_json(capsys, ["inspect", str(FIXTURE), "--json"])
    assert first["projects"][0]["source_sha256"] == second["projects"][0]["source_sha256"]


def test_validate_missing_root_is_clean_json(tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    code, payload = call_json(capsys, ["validate", str(tmp_path / "missing"), "--json"])
    assert code == 2 and payload["status"] == "error"
    assert payload["diagnostics"][0]["code"] == "PATH_NOT_FOUND"


def test_doctor_core_and_explicit_template(tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    code, data = call_json(capsys, ["doctor", "--json"])
    assert code == 0
    assert all(item["ok"] for item in data["checks"])
    code, data = call_json(capsys, ["doctor", "--template", str(tmp_path / "missing.docx"), "--json"])
    assert code == 4
    assert data["checks"][-1]["ok"] is False


def test_generate_refuses_missing_explicit_template(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    docx = tmp_path / "generated.docx"
    code, payload = call_json(capsys, [
        "generate", str(FIXTURE), "--template", str(tmp_path / "missing.docx"),
        "--output", str(docx), "--json",
    ])
    assert code == 2
    assert payload["diagnostics"][0]["code"] == "TEMPLATE_NOT_FOUND"
    assert not docx.exists()


def test_generate_json_same_word_engine(
    tmp_path: Path, capsys: pytest.CaptureFixture[str], monkeypatch: pytest.MonkeyPatch
) -> None:
    from docx import Document

    from pbip_documenter import cli

    def stub_build(*_args: Any, **_kwargs: Any) -> Any:
        doc = Document()
        doc.add_heading("Generated by shared engine", 1)
        return doc

    monkeypatch.setattr(cli, "build_doc", stub_build)
    out = tmp_path / "specification.docx"
    code, result = call_json(capsys, [
        "generate", str(FIXTURE), "--output", str(out), "--mode", "full", "--json",
    ])
    assert code == 0
    assert result["outputs"] == [str(out.resolve())]
    assert "Generated by shared engine" in "\n".join(p.text for p in Document(str(out)).paragraphs)


def test_strict_rejects_unparsed_tmdl_before_generation(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    model = tmp_path / "Bad.SemanticModel" / "definition" / "tables"
    model.mkdir(parents=True)
    (model / "Broken.tmdl").write_text("garbage syntax without a table declaration", encoding="utf-8")
    code, payload = call_json(capsys, ["validate", str(tmp_path), "--strict", "--json"])
    assert code == 3
    assert "TMDL_TABLE_UNPARSED" in [d["code"] for d in payload["projects"][0]["diagnostics"]]


def test_generate_strict_fails_before_creating_output(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    model = tmp_path / "Bad.SemanticModel" / "definition" / "tables"
    model.mkdir(parents=True)
    (model / "Broken.tmdl").write_text("this is not valid TMDL", encoding="utf-8")
    out = tmp_path / "keep.docx"
    out.write_bytes(b"PREVIOUS DOCUMENT")
    code, payload = call_json(capsys, ["generate", str(tmp_path), "--strict", "--output", str(out), "--json"])
    assert code == 3 and payload["outputs"] == []
    assert out.read_bytes() == b"PREVIOUS DOCUMENT"


def test_multiple_projects_explicit_output_rejected(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    root = tmp_path / "projects"
    for name in ("Alpha", "Beta"):
        (root / name / f"{name}.SemanticModel" / "definition" / "tables").mkdir(parents=True)
        (root / name / f"{name}.SemanticModel" / "definition" / "tables" / "A.tmdl").write_text(
            "table A\n\tcolumn B", encoding="utf-8"
        )
    out = tmp_path / "file.docx"
    code, result = call_json(capsys, ["generate", str(root), "--output", str(out), "--json"])
    assert code == 2 and result["diagnostics"][0]["code"] == "MULTIPLE_PROJECTS"
    assert not out.exists()


def test_legacy_cli_compatibility(capsys: pytest.CaptureFixture[str]) -> None:
    code = bootstrap.main(["--version"])
    # Both v1 version and historical CLI output remain supported.
    assert code == 0
    assert "pbip-documenter" in capsys.readouterr().out.lower()

def test_invalid_args_preserve_json_contract(capsys: pytest.CaptureFixture[str]) -> None:
    code, result = call_json(capsys, ["validate", "--unknown-option", "--json"])
    assert code == 2
    assert result["diagnostics"][0]["code"] == "ARGUMENT_INVALID"
    assert result["status"] == "error"
